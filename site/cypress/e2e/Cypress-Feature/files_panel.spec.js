import { getCurrentSemester } from '/cypress/support/utils.js';

function assertSubmissionsBrowserClosed() {
    cy.get('#div_viewer_sd1').should('not.be.visible');
}

function assertSubmissionsBrowserOpen() {
    // have to increase timeout so that the file can be loaded properly in the CI
    cy.get('#div_viewer_sd1', { timeout: 20000 }).should('be.visible');
}

function assertResultsBrowserClosed() {
    cy.get('#div_viewer_rd1').should('not.be.visible');
}

function assertResultsBrowserOpen() {
    // we can't check that it is visible because in the CI it's possible
    // that autograding hasn't finished yet
    cy.get('#div_viewer_rd1', { timeout: 20000 }).should('exist');
}

// for our testcase, we can assume dotfiles are not part of student submission
const single_file_submission_selector = '#div_viewer_sd1 div[id^=file_viewer_]:not([data-file_name^="."])';

function assertSingleFileSubmissionOpen() {
    // a single file submission should only include one file
    // (excluding autogenerated files that start with ".")
    cy.get(single_file_submission_selector).should('length', 1);
    cy.get(single_file_submission_selector).should('be.visible');
}

function assertSingleFileSubmissionClosed() {
    cy.get(single_file_submission_selector).should('length', 1);
    cy.get(single_file_submission_selector).should('not.be.visible');
}

const single_file_submission_clickable_selector = '#div_viewer_sd1 .openable-element-submissions:not([data-file_name^="."])';

function clickSingleFileSubmission() {
    cy.get(single_file_submission_clickable_selector).should('length', 1);
    cy.get(single_file_submission_clickable_selector).click();
}

describe('Test cases involving the files panel', () => {
    beforeEach(() => {
        cy.visit(['sample', 'gradeable', 'grading_homework', 'grading', 'details']);
        cy.login('instructor');
        cy.get('[data-testid="view-sections"]').uncheck();
        cy.get('#details-table').contains('hamile').siblings().eq(6).click();
        cy.get('#submission_browser_btn').click();
    });

    it('test the open/close submissions and results buttons', () => {
        assertSubmissionsBrowserClosed();
        assertResultsBrowserClosed();
        cy.get('#toggleSubmissionButton').click(); // open submissions browser
        assertSubmissionsBrowserOpen();
        assertResultsBrowserClosed();
        cy.get('#toggleSubmissionButton').click(); // close submissions browser
        assertSubmissionsBrowserClosed();
        assertResultsBrowserClosed();

        cy.get('#toggleResultButton').click(); // open results browser
        assertSubmissionsBrowserClosed();
        assertResultsBrowserOpen();
        cy.get('#toggleResultButton').click(); // close results browser
        assertSubmissionsBrowserClosed();
        assertResultsBrowserClosed();
    });

    it('test the auto open checkbox', () => {
        cy.get('#autoscroll_id').click();
        cy.get('#autoscroll_id').should('be.checked');

        cy.get('#grading-panel-student-name').should('contain.text', 'hamile');
        assertSubmissionsBrowserClosed();
        assertResultsBrowserClosed();
        cy.get('#submissions').click(); // open submissions browser
        cy.get('#results').click(); // open results browser
        assertSubmissionsBrowserOpen();
        assertResultsBrowserOpen();

        assertSingleFileSubmissionClosed();
        clickSingleFileSubmission(); // open this student's single file submission
        assertSingleFileSubmissionOpen();

        // this second student has the same submission as the first
        cy.get('#next-student').click();
        cy.get('#grading-panel-student-name').should('contain.text', 'browna');
        assertSubmissionsBrowserOpen();
        assertResultsBrowserOpen();
        assertSingleFileSubmissionOpen();

        // this third student has a different submission from the first and second
        cy.get('#next-student').click();
        cy.get('#grading-panel-student-name').should('contain.text', 'cummin');
        assertSubmissionsBrowserOpen();
        assertResultsBrowserOpen();
        assertSingleFileSubmissionClosed();

        // second submission name should still open; close it for later
        cy.get('#prev-student').click();
        cy.get('#grading-panel-student-name').should('contain.text', 'browna');
        assertSingleFileSubmissionOpen();
        clickSingleFileSubmission();
        assertSingleFileSubmissionClosed();

        // third submission name should still be closed; open it for later
        cy.get('#next-student').click();
        cy.get('#grading-panel-student-name').should('contain.text', 'cummin');
        assertSingleFileSubmissionClosed();
        clickSingleFileSubmission();
        assertSingleFileSubmissionOpen();

        // second submission name was closed; it should still be so
        cy.get('#prev-student').click();
        cy.get('#grading-panel-student-name').should('contain.text', 'browna');
        assertSingleFileSubmissionClosed();

        // third submission name was opened; it should still be so
        cy.get('#next-student').click();
        cy.get('#grading-panel-student-name').should('contain.text', 'cummin');
        assertSingleFileSubmissionOpen();

        // closing should work as well
        assertSubmissionsBrowserOpen();
        assertResultsBrowserOpen();
        cy.get('#submissions').click(); // close submissions browser
        cy.get('#results').click(); // close results browser
        assertSubmissionsBrowserClosed();
        assertResultsBrowserClosed();

        cy.get('#prev-student').click();
        cy.get('#grading-panel-student-name').should('contain.text', 'browna');
        assertSubmissionsBrowserClosed();
        assertResultsBrowserClosed();

        cy.get('#autoscroll_id').click();
        cy.get('#autoscroll_id').should('not.be.checked');
    });

    it('test the full panel view', () => {
        // this test is somewhat limited in what it can do because the page
        // displays an iframe which is inaccessible to Cypress for the most part
        // We just test that the full panel view opens, and that an iframe appears.

        cy.get('#submissions').click();
        cy.get('#file_viewer_full_panel_iframe').should('not.exist');
        cy.get('i[title="Show file in full panel"]').first().click();
        cy.get('#grading_file_name').should('contain', '.submit.timestamp');
        cy.get('#file_viewer_full_panel_iframe').should('be.visible');

        cy.get('[aria-label="Collapse File"]').click();
        cy.get('#file_viewer_full_panel_iframe').should('not.exist');
    });
});

describe('Test cases involving auto opening single file submissions', () => {
    it('test the single file auto open for text submissions', () => {
        cy.visit(['sample', 'gradeable', 'grading_homework', 'grading', 'details']);
        cy.login('instructor');
        cy.get('[data-testid="view-sections"]').uncheck();
        cy.get('#details-table').contains('browna').siblings().eq(6).click();
        cy.get('#submission_browser_btn').click();

        cy.get('#autoscroll_id').click();
        cy.get('#autoscroll_id').should('be.checked');

        // single file submission is opened if nothing else is open
        assertSingleFileSubmissionClosed();
        cy.reload();
        assertSubmissionsBrowserOpen();
        assertSingleFileSubmissionOpen();

        // closing the single file submission disables single file auto open
        clickSingleFileSubmission(); // close the submitted file
        assertSubmissionsBrowserOpen();
        cy.reload();
        assertSubmissionsBrowserOpen();
        assertSingleFileSubmissionClosed();

        cy.get('#submissions').click(); // close submissions browser
        assertSubmissionsBrowserClosed();
        cy.reload();
        assertSubmissionsBrowserOpen();
        assertSingleFileSubmissionOpen();

        // opening any other folder or file disables single file auto open
        assertResultsBrowserClosed();
        cy.get('#results').click(); // open results browser
        assertResultsBrowserOpen();
        assertSubmissionsBrowserOpen();
        assertSingleFileSubmissionOpen();

        clickSingleFileSubmission(); // close the submitted file
        cy.reload();
        assertResultsBrowserOpen();
        assertSubmissionsBrowserOpen();
        assertSingleFileSubmissionClosed();

        cy.get('#results').click(); // close results browser
        assertResultsBrowserClosed();
        cy.reload();
        assertResultsBrowserClosed();
        assertSubmissionsBrowserOpen();
        assertSingleFileSubmissionClosed();

        cy.get('#submissions').click(); // close submissions browser
        assertSubmissionsBrowserClosed();
        cy.reload();
        assertSubmissionsBrowserOpen();
        assertSingleFileSubmissionOpen();

        // switching between single file submission with different names works with auto open
        cy.get('#next-student').click();
        assertSubmissionsBrowserOpen();
        assertSingleFileSubmissionOpen();

        clickSingleFileSubmission(); // close the submitted file
        cy.get('#submissions').click(); // close submissions browser
        cy.get('#prev-student').click();
        assertSubmissionsBrowserOpen();
        assertSingleFileSubmissionOpen();

        // opening a submission with multiple files defaults to normal behavior
    });

    /*
        FIX ME! determining whether an image is open or closed in the grading panel requires some
        finnicky CSS because Cypress's (not.)be.visible gets tripped up by the #file-view's "hide" class
        combined with the use of display inline styling. A better approach to toggling the file view
        would be to toggle only classes or only inline styles, not both.
    */
    const file_view_selector = '#file-view[style^="display: flex;"]';

    function assertSingleImageSubmissionClosed() {
        cy.get(file_view_selector).should('not.exist');
    }

    function assertSingleImageSubmissionOpen() {
        cy.get(file_view_selector).should('length', 1);
    }

    function clickFileViewCollapseButton() {
        cy.get('a:has(i[title="Back"])', { timeout: 20000 }).should('be.visible').click();
    }

    it('test the single file auto open for image submissions', () => {
        cy.visit(['sample', 'gradeable', 'grading_homework_pdf', 'grading', 'details']);
        cy.login('instructor');
        cy.get('[data-testid="view-sections"]').uncheck();
        cy.get('#details-table').contains('beahaf').siblings().eq(6).click();
        cy.get('#submission_browser_btn').click();

        cy.get('#autoscroll_id').click();
        cy.get('#autoscroll_id').should('be.checked');

        // single image file submission is opened and fills the screen if nothing else is open
        assertSingleImageSubmissionClosed();
        cy.reload();
        assertSingleImageSubmissionOpen();

        // switching between single image file submission with different names works with auto open
        cy.get('#next-student').click();
        // cy.get('[data-testid="grading-panel-student-name"] b').contains('bitdiddle');
        assertSingleImageSubmissionOpen();

        clickFileViewCollapseButton();
        assertSingleImageSubmissionClosed();

        cy.get('#prev-student').click();
        // cy.get('[data-testid="grading-panel-student-name"] b').contains('beahaf');
        assertSingleImageSubmissionOpen();

        // wait for PDF to fully load in, or an error will occur when it's interrupted by logout
        cy.intercept(`/courses/${getCurrentSemester()}/sample/gradeable/grading_homework_pdf/encode_pdf`).as('pdf');
        cy.wait('@pdf');
    });

    it('test that multi-file submissions are unaffected', () => {
        cy.visit(['sample', 'gradeable', 'grading_pdf_peer_homework', 'grading', 'details']);
        cy.login('instructor');
        cy.get('[data-testid="view-sections"]').uncheck();
        cy.get('#details-table').contains('adamsg').siblings().eq(6).click();
        cy.get('#submission_browser_btn').click();

        cy.get('#autoscroll_id').click();
        cy.get('#autoscroll_id').should('be.checked');

        // opening a multi-file submission does not sure auto open single file logic
        cy.reload();
        assertSubmissionsBrowserClosed();
    });
});

describe('Test cases involving zooming images in the full panel view', () => {
    const imageName = 'blank_QR_numeric_id.png';

    function imageSize(dimension) {
        return cy.get('#annotatable-image').then(($img) => parseFloat($img.css(dimension)));
    }

    function openImage(name = imageName) {
        cy.get('#file-view').then(($view) => {
            if ($view.css('display') === 'flex') {
                cy.get('[aria-label="Collapse File"]').click();
                cy.get('#file-view').should('not.be.visible');
            }
        });
        cy.get('#div_viewer_sd1').then(($browser) => {
            if (!$browser.is(':visible')) {
                cy.get('#submissions').click();
            }
        });
        cy.get(`a.image-file[data-file_name="${name}"]`).click();
        cy.get('#annotatable-image').should(($img) => {
            expect($img[0].naturalWidth).to.be.greaterThan(0);
        });
    }

    function navigateToStudent(button, student, remaining = 30) {
        cy.waitPageChange(() => cy.get(button).click());
        cy.get('#grading-panel-student-name').invoke('text').then((name) => {
            if (!name.includes(student)) {
                expect(remaining, `navigation to ${student}`).to.be.greaterThan(0);
                navigateToStudent(button, student, remaining - 1);
            }
        });
    }

    before(() => {
        for (const [student, image] of [
            ['bitdiddle', `copy_of_more_autograding_examples/bulk_upload_pdfs/submissions/${imageName}`],
            ['browna', 'copy_of_more_autograding_examples/jupyter_notebook_autograding/config/test_output/graph.png'],
        ]) {
            cy.login(student);
            cy.visit(['sample', 'gradeable', 'open_homework']);
            cy.get('#startnew').then(($clearBtn) => {
                if (!$clearBtn.is(':disabled')) {
                    $clearBtn.click();
                }
            });
            cy.get('#upload1').selectFile([
                `cypress/fixtures/${image}`,
                'cypress/fixtures/words_249.pdf',
            ], { action: 'drag-drop' });
            cy.waitPageChange(() => {
                cy.get('#submit').click();
            });
            cy.get('#submitted-files > div').should('contain', image.split('/').pop());
            cy.get('.auto-results-queue-msg', { timeout: 120000 }).should('not.exist');
            cy.logout();
        }
    });

    beforeEach(() => {
        cy.login('instructor');
        cy.visit(['sample', 'gradeable', 'open_homework', 'grading', 'details']);
        cy.clearLocalStorage('image-scale');
        cy.clearLocalStorage('pdf-scale');
        cy.window().then((win) => {
            win.localStorage.setItem('general-setting-arrow-function', 'default');
            win.localStorage.setItem('general-setting-navigate-assigned-students-only', 'false');
        });
        cy.get('[data-testid="view-sections"]').uncheck();
        cy.get('#details-table').contains('tr', 'bitdiddle').find('[data-testid="grade-button"]').click();
        cy.get('#submission_browser_btn').click();
        openImage();
    });

    afterEach(() => {
        cy.clearLocalStorage('image-scale');
        cy.clearLocalStorage('pdf-scale');
    });

    it('test the zoom buttons on an image submission', () => {
        cy.get('#file-zoom-display').should('have.text', '100%');
        imageSize('width').then((fitWidth) => {
            cy.get('[aria-label="Zoom In"]').click();
            cy.get('[aria-label="Zoom In"]').click();
            cy.get('#file-zoom-display').should('have.text', '120%');
            imageSize('width').should('be.closeTo', fitWidth * 1.2, 2);

            // zoom never goes below the size that fits the panel
            cy.get('[aria-label="Zoom Out"]').click();
            cy.get('[aria-label="Zoom Out"]').click();
            cy.get('[aria-label="Zoom Out"]').click();
            cy.get('#file-zoom-display').should('have.text', '100%');
            imageSize('width').should('be.closeTo', fitWidth, 2);

            for (let i = 0; i < 41; i++) {
                cy.get('[aria-label="Zoom In"]').click();
            }
            cy.get('#file-zoom-display').should('have.text', '500%');
            imageSize('width').should('be.closeTo', fitWidth * 5, 2);
        });

        cy.get('[aria-label="Collapse File"]').click();
        cy.get('#annotatable-image').should('not.exist');
    });

    it('retains zoom through student navigation and reload, fitting each image separately', () => {
        imageSize('width').then((firstFitWidth) => {
            for (let i = 0; i < 3; i++) {
                cy.get('[aria-label="Zoom In"]').click();
            }
            cy.get('#file-zoom-display').should('have.text', '130%');
            imageSize('width').should('be.closeTo', firstFitWidth * 1.3, 2);

            navigateToStudent('#next-student', 'browna');
            cy.get('#grading-panel-student-name').should('contain.text', 'browna');
            openImage('graph.png');
            cy.get('#file-zoom-display').should('have.text', '130%');
            imageSize('height').then((zoomedHeight) => {
                for (let i = 0; i < 3; i++) {
                    cy.get('[aria-label="Zoom Out"]').click();
                }
                cy.get('#file-zoom-display').should('have.text', '100%');
                imageSize('height').should('be.closeTo', zoomedHeight / 1.3, 2);
                for (let i = 0; i < 3; i++) {
                    cy.get('[aria-label="Zoom In"]').click();
                }
            });

            navigateToStudent('#prev-student', 'bitdiddle');
            cy.get('#grading-panel-student-name').should('contain.text', 'bitdiddle');
            openImage();
            cy.get('#file-zoom-display').should('have.text', '130%');
            imageSize('width').should('be.closeTo', firstFitWidth * 1.3, 2);

            cy.reload();
            openImage();
            cy.get('#file-zoom-display').should('have.text', '130%');
            imageSize('width').should('be.closeTo', firstFitWidth * 1.3, 2);
            cy.screenshot('image-zoom-after-student-navigation-and-reload');
        });
    });

    it('defaults to fitted size for invalid saved zoom levels', () => {
        imageSize('width').then((fitWidth) => {
            for (const value of ['', 'invalid', '1.3junk', 'NaN', 'Infinity', '0.9', '5.1']) {
                cy.window().then((win) => win.localStorage.setItem('image-scale', value));
                openImage();
                cy.get('#file-zoom-display').should('have.text', '100%');
                imageSize('width').should('be.closeTo', fitWidth, 2);
            }
        });
    });

    it('keeps image and PDF zoom independent', () => {
        cy.get('[aria-label="Zoom In"]').click();
        cy.get('#file-zoom-display').should('have.text', '110%');
        cy.window().then((win) => win.localStorage.setItem('pdf-scale', '1.5'));
        cy.get('[aria-label="Collapse File"]').click();
        cy.get('#file-view').should('not.be.visible');
        cy.get('[data-testid="submission-browser-file"][data-file-name="words_249.pdf"] [aria-label="Show file in full panel"]').click();
        cy.get('#file-zoom-display').should('have.text', '150%');
        cy.get('[aria-label="Zoom In"]').click();
        cy.get('#file-zoom-display').should('have.text', '160%');
        openImage();
        cy.get('#file-zoom-display').should('have.text', '110%');
        cy.window().then((win) => {
            expect(win.localStorage.getItem('image-scale')).to.equal('1.1');
            expect(win.localStorage.getItem('pdf-scale')).to.equal('1.6');
        });
    });

    it('keeps markers aligned through restored zoom, editing, cancel, save, and cleanup', () => {
        cy.window().then((win) => win.localStorage.setItem('image-scale', '1.3'));
        openImage();
        cy.window().then((win) => {
            const img = win.document.getElementById('annotatable-image');
            const state = {
                width: img.naturalWidth,
                height: img.naturalHeight,
                markers: [{
                    typeName: 'FrameMarker',
                    left: img.naturalWidth * 0.1,
                    top: img.naturalHeight * 0.1,
                    width: img.naturalWidth * 0.2,
                    height: img.naturalHeight * 0.2,
                    rotationAngle: 0,
                    strokeColor: '#ff0000',
                    strokeWidth: 2,
                }],
            };
            // Normal uploads do not enable annotations; initialize the same viewer used by bulk uploads.
            win.initImageAnnotation('open_homework', 'bitdiddle', 'instructor', imageName, '', win.csrfToken, false, {
                instructor: JSON.stringify(state),
            });
        });

        function assertMarkerAlignment() {
            cy.get('#annotation-marker-view').should(($view) => {
                const view = $view[0];
                expect(view.markers).to.have.length(1);
                const image = view.shadowRoot.querySelector('img').getBoundingClientRect();
                const marker = view.markers[0].container.getBoundingClientRect();
                expect(image.width).to.be.greaterThan(0);
                expect((marker.left - image.left) / image.width).to.be.closeTo(0.1, 0.01);
                expect((marker.top - image.top) / image.height).to.be.closeTo(0.1, 0.01);
                expect(marker.width / image.width).to.be.closeTo(0.2, 0.01);
                expect(marker.height / image.height).to.be.closeTo(0.2, 0.01);
            });
        }

        cy.get('#file-zoom-display').should('have.text', '130%');
        assertMarkerAlignment();
        cy.get('[aria-label="Zoom In"]').click();
        cy.get('#file-zoom-display').should('have.text', '140%');
        assertMarkerAlignment();
        cy.window().then((win) => win.addAnnotations());
        cy.get('#global-annotation-editor').should(($editor) => {
            expect($editor[0].markerArea.getState().markers).to.have.length(1);
        });
        cy.get('#global-annotation-editor').shadow().find('[aria-label="Close"]').click();
        assertMarkerAlignment();
        cy.window().then((win) => win.addAnnotations());
        cy.get('#global-annotation-editor').should(($editor) => {
            expect($editor[0].markerArea.getState().markers).to.have.length(1);
        });
        cy.get('#global-annotation-editor').shadow().find('[aria-label="OK"]').click();
        cy.get('#global-annotation-editor-wrapper').should('not.be.visible');
        assertMarkerAlignment();
        cy.intercept('POST', '**/img/annotations', { status: 'success' }).as('saveAnnotations');
        cy.window().then((win) => win.saveAnnotations());
        cy.wait('@saveAnnotations').then(({ request }) => {
            const annotations = typeof request.body === 'string'
                ? new URLSearchParams(request.body).get('annotations')
                : request.body.annotations;
            expect(JSON.parse(annotations).markers).to.have.length(1);
        });
        cy.screenshot('image-zoom-marker-alignment');
        cy.window().then((win) => win.cleanupAnnotationEditor());
        cy.get('#global-annotation-editor-wrapper').should('not.exist');
        cy.get('#annotation-marker-view').should('not.exist');
        cy.get('#annotatable-image').should(($img) => {
            expect($img[0].dataset.zoom).to.equal('1.4');
        });
        cy.get('#file-zoom-display').should('have.text', '140%');
    });
});
